const { app, ipcMain } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { pathToFileURL } = require('node:url')
process.env.KAPANIS_SMOKE_TEST = '1'
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
let runtime
;(async () => {
  app.setPath('userData', await fs.mkdtemp(path.join(os.tmpdir(), 'eon-update-ui-')))
  await app.whenReady()
  const { startEon2Runtime } = await import(pathToFileURL(path.resolve('dist-electron/electron/eon2/Eon2Runtime.js')).href)
  runtime = await startEon2Runtime(path.resolve('dist-electron/electron/eon2/preload.cjs'), pathToFileURL(path.resolve('dist/index.html')).href)
  const win = runtime.windows.getMainWindow()
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve))
  const js = code => win.webContents.executeJavaScript(code)
  win.unmaximize(); win.setContentSize(1440, 900); win.show()
  await wait(600)
  await js(`document.querySelector('[aria-label="Rehberi kapat"]')?.click()`)
  let installs = 0
  ipcMain.removeHandler('eon2:updates:install')
  ipcMain.handle('eon2:updates:install', () => { installs++ })
  const state = { desktop: { phase:'current', currentVersion:'2.0.0-preview.2', message:'Eon güncel' },
    mobile:{ phase:'current', message:'Telefon güncel', devices:[] } }
  const send = async patch => { Object.assign(state.desktop, patch); win.webContents.send('eon2:updates:changed', state); await wait(150) }
  await send({ phase:'current' })
  assert.equal(await js(`!!document.querySelector('.eon-update-title')`), false)
  await send({ phase:'downloading', availableVersion:'2.0.0-preview.3', progress:42, message:'Arka planda indiriliyor' })
  assert.match(await js(`document.querySelector('.eon-update-title').textContent`), /42/)
  await js(`document.querySelector('.eon-update-title').click()`)
  await wait(250)
  assert.equal(await js(`document.querySelector('.eon-updates progress').value`), 42)
  await send({ phase:'downloaded', progress:100, message:'Kuruluma hazır' })
  assert.equal(installs, 0)
  await js(`document.querySelector('.eon-updates').scrollIntoView({block:'start'})`)
  await wait(350)
  await fs.mkdir('docs/eon2/qa-updates', { recursive:true })
  await fs.writeFile('docs/eon2/qa-updates/desktop-ready.png', (await win.webContents.capturePage()).toPNG())
  await js(`[...document.querySelectorAll('.eon-updates button')].find(x=>x.textContent==='Yeniden başlat ve kur').click()`)
  await wait(100)
  assert.equal(await js(`document.querySelector('.eon-update-confirm').matches(':modal')`), true)
  await js(`[...document.querySelectorAll('.eon-update-confirm button')].find(x=>x.textContent==='Daha sonra').click()`)
  await wait(100); assert.equal(installs, 0)
  for (const width of [720,900,1440,1920,3840]) {
    win.setContentSize(width, 900); await wait(100)
    assert.ok(await js(`document.documentElement.scrollWidth <= innerWidth + 2`), `overflow at ${width}`)
  }
  win.setContentSize(1440,900)
  await js(`window.kapanisDesktop.invoke('eon2:settings:set',{key:'theme',value:'light'})`)
  await wait(300)
  await js(`document.querySelector('.eon-updates').scrollIntoView({block:'start'})`)
  await wait(250)
  await fs.writeFile('docs/eon2/qa-updates/desktop-light.png', (await win.webContents.capturePage()).toPNG())
  await js(`[...document.querySelectorAll('.eon-updates button')].find(x=>x.textContent==='Yeniden başlat ve kur').click()`)
  await wait(100)
  await js(`[...document.querySelectorAll('.eon-update-confirm button')].find(x=>x.textContent==='Kaydettim, kur').click()`)
  await wait(100); assert.equal(installs, 1)
  console.log('Update UI smoke passed: hidden/current, progress, settings, native modal, cancel/install, light, five widths; installer mocked')
  runtime.close(); app.exit(0)
})().catch(error => { console.error(error); runtime?.close(); app.exit(1) })
