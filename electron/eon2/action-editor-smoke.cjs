const { app, shell } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
process.env.KAPANIS_SMOKE_TEST = '1'
let runtime
;(async () => {
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'eon-action-editor-'))
  app.setPath('userData', profile)
  await app.whenReady()
  const { startEon2Runtime } = await import(pathToFileURL(path.resolve('dist-electron/electron/eon2/Eon2Runtime.js')).href)
  runtime = await startEon2Runtime(path.resolve('dist-electron/electron/eon2/preload.cjs'), pathToFileURL(path.resolve('dist/index.html')).href)
  const win = runtime.windows.getMainWindow()
  win.webContents.on('console-message', (_e, level, message) => { if (level >= 2) console.error('renderer:', message) })
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve))
  win.show()
  win.focus()
  const js = code => win.webContents.executeJavaScript(code)
  const settle = () => new Promise(resolve => setTimeout(resolve, 300))
  await settle()
  await js(`document.querySelector('[aria-label="Rehberi kapat"]')?.click(); [...document.querySelectorAll('.eon2-nav-item')].find(b=>b.title==='PC Kısayolları').click()`)
  await settle()
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Kısayol ekle')).click()`)
  await settle()
  const exe = path.join(process.env.WINDIR, 'System32', 'notepad.exe')
  const link = path.join(profile, 'Notepad.lnk')
  assert.equal(shell.writeShortcutLink(link, { target: exe, args: '', cwd: path.dirname(exe) }), true)
  const imported = await js(`window.kapanisDesktop.invoke('eon2:actions:drop', {paths:[${JSON.stringify(link)}]})`)
  assert.equal(imported.kind, 'application')
  assert.equal(imported.name, 'Notepad')
  assert.equal(imported.target, link)
  win.webContents.debugger.attach('1.3')
  const rect = await js(`(()=>{const r=document.querySelector('.eon2-action-import').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  const data = { items: [], files: [exe], dragOperationsMask: 1 }
  for (const type of ['dragEnter', 'dragOver', 'drop']) {
    await win.webContents.debugger.sendCommand('Input.dispatchDragEvent', { type, ...rect, data })
  }
  await settle()
  assert.equal(await js(`document.querySelector('dialog input[required]').value.toLowerCase()`), 'notepad')
  assert.equal(await js(`document.querySelector('dialog select').value`), 'application')
  await js(`document.querySelector('.eon2-icon-options button[title="Oyun"]').click()`)
  assert.equal(await js(`document.querySelector('.eon2-icon-options button[title="Oyun"]').getAttribute('aria-pressed')`), 'true')
  const output = path.resolve('build/action-editor-qa')
  await fs.mkdir(output, {recursive:true})
  for (const [width,height] of [[720,900],[900,720],[1440,900],[3840,2160]]) {
    win.setContentSize(width,height)
    await settle()
    await js('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
    assert.equal(await js(`document.querySelector('dialog').scrollWidth <= document.querySelector('dialog').clientWidth`), true)
    await fs.writeFile(path.join(output, `editor-${width}.png`), (await win.webContents.capturePage()).toPNG())
  }
  await js(`document.querySelector('dialog form').requestSubmit()`)
  await settle()
  assert.equal(await js(`!!document.querySelector('dialog')`), false)
  const stored = await js(`window.kapanisDesktop.invoke('eon2:actions:list')`)
  const saved = stored.actions.find(a=>a.name.toLowerCase()==='notepad')
  assert.equal(saved.icon, 'gamepad')
  assert.equal(saved.target, exe)
  const deck = await js(`window.kapanisDesktop.invoke('eon2:deck:get')`)
  assert.equal(deck.actions.find(a=>a.id===saved.id).icon, 'gamepad')
  await js(`[...document.querySelectorAll('.eon2-nav-item')].find(b=>b.title==='Ayarlar').click()`)
  await settle()
  await js(`[...document.querySelectorAll('.eon2-theme-swatch')].find(b=>b.textContent.includes('Aydınlık')).click()`)
  await settle()
  await js(`[...document.querySelectorAll('.eon2-nav-item')].find(b=>b.title==='PC Kısayolları').click()`)
  await settle()
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Kısayol ekle')).click()`)
  win.setContentSize(1440,900)
  await settle()
  assert.equal(await js("document.querySelector('.eon2-app').classList.contains('eon2-theme-light')"), true)
  await fs.writeFile(path.join(output, 'editor-light.png'), (await win.webContents.capturePage()).toPNG())
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' })
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' })
  await settle()
  assert.equal(await js(`!!document.querySelector('dialog')`), false)
  console.log('PASS: native file drop, .lnk detection, icon selection/save/deck, Escape, dark/light responsive captures')
  win.webContents.debugger.detach()
  runtime.close()
  app.exit(0)
})().catch(async error => { console.error(error); try {runtime?.close()} catch {} app.exit(1) })


setTimeout(() => { console.error('Shortcut smoke timeout'); runtime?.close(); app.exit(1) }, 90000).unref()
